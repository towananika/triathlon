const assert = require('node:assert/strict');
const D = require('./development.js');
const rich = () => ({pop:100,short:0,mood:70,stock:{food:100000,mat:100000,goods:100000},price:{food:1,goods:2},income:5,unemp:.03});
const nation = {name:'検証国',budget:1000};
const c = D.create('検証国');
assert.equal(D.stage(c),'基盤整備');
const poor = rich(); poor.short=1; poor.stock={food:0,mat:0,goods:0};
for(let day=0;day<3650;day+=30) D.step(c,[poor],nation,day);
assert.equal(c.research,0); assert.equal(c.formedDay,null);
const good=D.create('検証国'),p=rich();
for(let day=0;day<36500;day+=30) {p.stock={food:100000,mat:100000,goods:100000};D.step(good,[p],nation,day);}
assert.equal(D.stage(good),'現代基盤'); assert.notEqual(good.modernDay,null);
assert(Object.values(good.services).every(v=>v>=.8 && v<=1));
const cost=D.costOfLiving(rich(),{});
assert.equal(cost.balance,null); assert.equal(cost.income,null);
const inflation=rich();inflation.price.food=2;
assert(D.costOfLiving(inflation,{}).expenses.food>cost.expenses.food);
const renting=D.costOfLiving(rich(),{housing:'rent',income:100,transport:0});
assert.equal(renting.balance,100-renting.total);
assert.throws(()=>D.costOfLiving(rich(),{income:-1}),RangeError);
assert.equal(D.costOfLiving(rich(),{housing:'rent',income:100}).total,null);
const financed=D.costOfLiving(rich(),{housing:'family',income:20,support:30,transport:5});
assert.equal(financed.income,50);
assert.equal(financed.balance,50-financed.total);
assert.equal(D.costOfLiving(rich(),{support:30}).income,null);
const fixture=rich(), previousMat=fixture.stock.mat, previousGoods=fixture.stock.goods;
D.step(D.create('資源検証'),[fixture],nation,0);
assert(fixture.stock.mat<previousMat && fixture.stock.goods<previousGoods);
assert(fixture.stock.mat>=0 && fixture.stock.goods>=0);
