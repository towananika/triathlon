const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
const path = require('node:path');
(async()=>{
  const browser = await chromium.launch({headless:true,channel:'chrome'});
  try {
    const context = await browser.newContext({acceptDownloads:true,reducedMotion:'reduce'});
    const page = await context.newPage();
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    const url=process.env.PAGE_URL||pathToFileURL(path.join(__dirname,'index.html')).href;
    await page.goto(url+'#atlas');
    await page.locator('#atlas').waitFor({state:'visible'});
    assert((await page.locator('.earth-land').getAttribute('d')).length>1000);
    assert.equal(await page.locator('.earth-land').count(),1);
    assert.equal(await page.locator('.earth-candidate').count(),5);
    await page.locator('#region-choice').selectOption('east-asia');
    assert.match(await page.locator('#atlas-coordinates').innerText(),/37.57/);
    await page.locator('#city-name').fill('<img src=x onerror=alert(1)>');
    await page.locator('#city-name').dispatchEvent('change');
    await page.locator('#city-priority').selectOption('nature');
    assert.match(await page.locator('#city-summary').innerText(),/自然/);
    assert.equal(await page.locator('#city-summary img').count(),0);
    await page.reload();
    assert.equal(await page.locator('#city-priority').inputValue(),'nature');
    assert.match(await page.locator('#city-name').inputValue(),/<img/);
    await page.locator('#city-name').fill('青波・新しい街の案');
    await page.locator('#tab-characters').click();
    await page.locator('[data-person="mage"]').click();
    assert.match(await page.locator('#person-facts').innerText(),/全国1位/);
    assert.match(await page.locator('#person-facts').innerText(),/謙虚/);
    await page.locator('#person-note').fill('謙虚さを会話でも表したい');
    await page.locator('#person-note').dispatchEvent('change');
    await page.reload();
    assert.equal(await page.locator('#person-note').inputValue(),'謙虚さを会話でも表したい');
    await page.locator('[data-person="knight"]').click();
    assert.match(await page.locator('#person-facts').innerText(),/裕福/);
    assert.equal(await page.locator('#person-note').inputValue(),'');
    await page.locator('[data-person="ranger"]').click();
    assert.match(await page.locator('#person-facts').innerText(),/芯/);
    await page.locator('[data-person="elemental"]').click();
    assert.match(await page.locator('#person-facts').innerText(),/生意気/);
    await page.goto(url+'#civilizations');
    await page.locator('#civilizations').waitFor({state:'visible'});
    assert.match(await page.locator('#civilizations').innerText(),/共和制/);
    assert.match(await page.locator('#civilizations').innerText(),/実力主義帝国/);
    assert.match(await page.locator('#civilizations').innerText(),/ライン式/);
    assert.match(await page.locator('#civilizations').innerText(),/円式/);
    assert.match(await page.locator('#civilizations').innerText(),/改神国/);
    assert.match(await page.locator('#civilizations').innerText(),/立憲君主制/);
    assert.match(await page.locator('#civilizations').innerText(),/議会共和制/);
    await page.goto(url+'#education');
    await page.locator('#education').waitFor({state:'visible'});
    for(const name of ['帝国学校','士官学校','国立学校','市立学校','公立学校','神学校','魔法学校','海洋学校']) assert.match(await page.locator('#education').innerText(),new RegExp(name));
    await page.goto(url+'#atlas');
    await page.locator('#atlas').waitFor({state:'visible'});
    const download=page.waitForEvent('download');
    await page.locator('#export-draft').click();
    const exported=await download;
    assert.match(exported.suggestedFilename(),/triathlon.*json/);
    assert.equal(await exported.failure(),null);
    await page.locator('#earth-map').scrollIntoViewIfNeeded();
    const point=await page.locator('#earth-map').evaluate(svg=>{
      const xy=d3.geoNaturalEarth1().fitExtent([[16,16],[944,494]],{type:'Sphere'})([-100,45]);
      const p=svg.createSVGPoint();p.x=xy[0];p.y=xy[1];const q=p.matrixTransform(svg.getScreenCTM());return{x:q.x,y:q.y};
    });
    await page.mouse.click(point.x,point.y);
    assert.equal(await page.locator('#region-choice').inputValue(),'custom');
    for(const width of [320,390,1280]) {
      await page.setViewportSize({width,height:900});
      for(const section of ['atlas','dossier','civilizations','education']) {
        await page.goto(url+'#'+section);
        await page.locator('#'+section).waitFor({state:'visible'});
        assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
        await page.locator('#'+section).screenshot({path:path.join(__dirname,`${section}-${width}.png`)});
      }
    }
    assert.deepEqual(errors,[]);
    await page.evaluate(()=>localStorage.setItem('triathlon-world-draft-v1','{broken'));
    await page.reload();
    assert.equal(await page.locator('#city-name').inputValue(),'');
    assert.equal(await page.locator('#city-priority').inputValue(),'community');
    await page.goto(url+'#atlas');
    await page.locator('#city-name').fill('削除確認のテスト');
    page.once('dialog',dialog=>dialog.dismiss());
    await page.locator('#clear-draft').click();
    assert.equal(await page.locator('#city-name').inputValue(),'削除確認のテスト');
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('#clear-draft').click();
    assert.equal(await page.locator('#city-name').inputValue(),'');
    await page.evaluate(()=>localStorage.setItem('triathlon-world-draft-v1',JSON.stringify({version:1,site:{lon:999,lat:NaN},priority:'bad',person:'bad',notes:[]})));
    await page.reload();
    assert.equal(await page.locator('#city-priority').inputValue(),'community');
    assert.deepEqual(errors,[]);
    console.log('Verified Earth geometry, region selection, planning draft persistence, safe text, dossiers, individual notes, export and responsive layouts.');
    await context.close();
    const blocked=await browser.newContext();
    await blocked.addInitScript(()=>{Storage.prototype.setItem=function(){throw new DOMException('Blocked','SecurityError');};});
    const fallback=await blocked.newPage();
    await fallback.goto(url+'#atlas');
    await fallback.locator('#city-name').fill('保存不可のテスト');
    assert.match(await fallback.locator('#draft-status').innerText(),/保存できません/);
    await blocked.close();
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
